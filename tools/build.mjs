#!/usr/bin/env node
// Wraps every shaders/<id>.glsl preset for Qt (GLSL 440 → .qsb) and for the web preview (GLSL ES 3.00).
// Usage: node tools/build.mjs [--check]   (--check also validates the web variant with glslangValidator)
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const shaderDir = join(root, "shaders");
const qtOut = join(root, "quickshell", "shaders");
const QSB = process.env.QSB || "/usr/lib/qt6/bin/qsb";
const check = process.argv.includes("--check");

const UNIFORMS = [
  ["float", "iTime"], ["vec2", "iResolution"], ["float", "uFlow"],
  ["float", "uLevel"], ["float", "uBass"], ["float", "uMid"], ["float", "uHigh"], ["float", "uBeat"],
  ["vec4", "uSpec0"], ["vec4", "uSpec1"], ["vec4", "uSpec2"], ["vec4", "uSpec3"],
  ["vec4", "uColor1"], ["vec4", "uColor2"], ["vec4", "uColor3"], ["float", "uIntensity"],
];

const HELPERS = `
float spec(int i) {
    i = clamp(i, 0, 15);
    vec4 v = i < 4 ? uSpec0 : i < 8 ? uSpec1 : i < 12 ? uSpec2 : uSpec3;
    return v[i & 3];
}
float specAt(float x) {
    float f = clamp(x, 0.0, 1.0) * 15.0;
    int i = int(floor(f));
    return mix(spec(i), spec(i + 1), fract(f));
}
`;

function qtSource(body) {
  return `#version 440
layout(location = 0) in vec2 qt_TexCoord0;
layout(location = 0) out vec4 qt_FragColor;
layout(std140, binding = 0) uniform buf {
    mat4 qt_Matrix;
    float qt_Opacity;
${UNIFORMS.map(([t, n]) => `    ${t} ${n};`).join("\n")}
};
${HELPERS}
#line 1
${body}
void main() {
    vec4 c = vec4(0.0);
    mainImage(c, vec2(qt_TexCoord0.x, 1.0 - qt_TexCoord0.y) * iResolution);
    qt_FragColor = c * qt_Opacity;
}
`;
}

function webSource(body) {
  return `#version 300 es
precision highp float;
precision highp int;
${UNIFORMS.map(([t, n]) => `uniform ${t} ${n};`).join("\n")}
out vec4 rd_FragColor;
${HELPERS}
#line 1
${body}
void main() {
    vec4 c = vec4(0.0);
    mainImage(c, gl_FragCoord.xy);
    rd_FragColor = c;
}
`;
}

function meta(body, id) {
  const tag = (k) => body.match(new RegExp(`//\\s*@${k}\\s+(.+)`))?.[1].trim() ?? "";
  return { id, name: tag("name") || id, description: tag("description"), author: tag("author") };
}

mkdirSync(qtOut, { recursive: true });
const presets = [];
let failed = 0;
for (const file of readdirSync(shaderDir).filter((f) => f.endsWith(".glsl")).sort()) {
  const id = file.slice(0, -5);
  const body = readFileSync(join(shaderDir, file), "utf8");
  try {
    const frag = join(qtOut, `${id}.frag`);
    writeFileSync(frag, qtSource(body));
    execFileSync(QSB, ["--glsl", "100 es,120,150", "--qt6", "-o", `${frag}.qsb`, frag], { stdio: "pipe" });
    if (check) {
      const web = join(tmpdir(), `rd-${id}.frag`);
      writeFileSync(web, webSource(body));
      execFileSync("glslangValidator", [web], { stdio: "pipe" });
    }
    presets.push({ ...meta(body, id), source: webSource(body) });
    console.log(`ok   ${id}`);
  } catch (e) {
    failed++;
    console.error(`FAIL ${id}\n${(e.stdout || "") + (e.stderr || e.message)}`);
  }
}

writeFileSync(
  join(root, "web", "shaders.generated.js"),
  `// Generated by tools/build.mjs — do not edit.\nwindow.RD_PRESETS = ${JSON.stringify(presets, null, 1)};\n`,
);
console.log(`${presets.length} preset(s) built${failed ? `, ${failed} failed` : ""}`);
process.exit(failed ? 1 : 0);
